#!/usr/bin/env node
/*
 * generate-api-reference — the client API as a page, generated from its source.
 *
 * The one artefact every abap2UI5 app is written against is a single
 * interface: z2ui5_if_client, handed to the app as `client` on every
 * roundtrip. The interface carries its own documentation - hundreds of
 * ABAP-Doc lines on the methods, the parameters and the constants - and until
 * now the only way to read any of it was to open the source file. No page on
 * this site listed the API; a reader (or an agent) asking "what can client->
 * do" had to reverse it out of the cookbook examples.
 *
 * So the reference is GENERATED, the way the Working Samples blocks are:
 * nothing about the interface is retyped here, because a hand-written API
 * page is wrong the release after it is written. Two artefacts, both
 * committed:
 *
 *   docs/resources/api.md            the page - methods grouped and ordered,
 *                                    parameters with types and defaults, the
 *                                    cs_* constants, all of it between markers;
 *                                    the intro outside the markers is prose
 *                                    and is written by hand
 *   docs/public/api/client-api.json  the same model as one JSON document, so
 *                                    tooling fetches one URL instead of
 *                                    parsing a page
 *
 * TRUTH is the release, never main - the same rule check-api-names and
 * check-examples follow, reading the same pin (lib/release.mjs) and the same
 * source file (lib/client-interface.mjs). A2UI5_REF overrides it for a canary
 * run against main.
 *
 * Committed rather than build-time (like llms.txt) because it is a claim
 * about ANOTHER repository at a pinned release, not a projection of the pages
 * next to it - exactly the samples-block case, and it gets the same freshness
 * gate: --check regenerates and fails when the committed copy differs. When
 * the interface cannot be fetched, --check SAYS SO and passes - a
 * documentation gate must not go red because github.com is unreachable, and
 * must not claim to have verified something it did not. Generation without
 * --check fails instead: there is nothing to write.
 *
 *   node scripts/generate-api-reference.mjs            rewrite page + JSON
 *   node scripts/generate-api-reference.mjs --check    fail if a rewrite
 *                                                      would change anything
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { declaredRelease } from './lib/release.mjs';
import { fetchInterface, parseInterface, interfacePath } from './lib/client-interface.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = path.join(ROOT, 'docs', 'resources', 'api.md');
const JSON_OUT = path.join(ROOT, 'docs', 'public', 'api', 'client-api.json');
const CHECK = process.argv.includes('--check');

const START = '<!-- api:start (generated by scripts/generate-api-reference.mjs — do not edit) -->';
const END = '<!-- api:end -->';
const SITE = 'https://abap2ui5.github.io/docs';

/* ------------------------------------------------------------- the source */

const REF = process.env.A2UI5_REF || declaredRelease(ROOT);
if (!REF) {
  console.log('the three places naming the release DISAGREE, so there is nothing to pin to.');
  console.log('SKIPPED: run npm run check:version.');
  process.exit(0);
}

let iface;
try {
  iface = await fetchInterface(REF);
} catch (err) {
  console.log(`z2ui5_if_client at ${REF}: not resolved (${err.message})`);
  if (CHECK) {
    console.log('SKIPPED: nothing was verified.');
    process.exit(0);
  }
  console.error('nothing to generate from - try again with a network.');
  process.exit(1);
}

const model = parseInterface(iface);
if (model.methods.length < 20 || !model.constants.some((c) => c.name === 'cs_event' && c.members.length > 10)) {
  console.log(`z2ui5_if_client at ${REF} parsed to almost nothing - the interface changed shape.`);
  console.log('Fix the parser in scripts/lib/client-interface.mjs, or this reference silently thins out.');
  process.exit(1);
}

/* ------------------------------------------------------- grouping the methods */

/* Derived from the interface's own naming, not invented here: the prefixes ARE
 * its structure (view_*, nest*, popup_* and popover_*, _bind*, message_*, …).
 * First match wins, so the narrower pattern stands before the wider one. */
const RULES = [
  ['App lifecycle', /^check_on_/],
  ['Data binding', /^_bind/],
  ['Main view', /^view_/],
  ['Nested views', /^nest/],
  ['Popups and popovers', /^(popup|popover)_/],
  ['Messages', /^message_/],
  ['App navigation', /^(_event_nav|nav_app_|get_app|check_app)/],
  ['Events and frontend actions', /^(_event|follow_up_action)/],
  ['Reading the request', /^get(_event(_arg)?)?$/],
];

/* The order a reader meets them in an app: the dispatcher first, then the
 * view, then what the view is wired to. */
const ORDER = [
  'App lifecycle',
  'Main view',
  'Nested views',
  'Popups and popovers',
  'Data binding',
  'Events and frontend actions',
  'Reading the request',
  'Messages',
  'App navigation',
  'Session and app state',
  'Other',
];

const groupOf = (name) => {
  for (const [group, re] of RULES) if (re.test(name)) return group;
  if (name.startsWith('set_')) return 'Session and app state';
  return 'Other';
};
for (const m of model.methods) m.group = groupOf(m.name);

/* ---------------------------------------------------------------- markdown */

/** `<` becomes an HTML tag in VitePress prose, but stays literal inside an
 *  inline-code span - so escape around the spans, never inside them. */
const prose = (s) => s
  .split(/(`[^`]*`)/)
  .map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;')))
  .join('');

/** A table cell: prose, on one line, with every `|` escaped (GFM reads an
 *  escaped pipe as a pipe even inside a code span). */
const cell = (s) => prose(s).replace(/\|/g, '\\|').replace(/\s*\r?\n\s*/g, ' ');

const isObsolete = (doc) => /^obsolete\b/i.test(doc[0] ?? '');

const defaultCell = (p) => {
  if (p.default === undefined) return p.optional ? '*optional*' : '';
  const literal = /^`(.*)`$/.exec(p.default);
  if (literal) return literal[1] === '' ? '*(empty)*' : `\`${literal[1]}\``;
  return `\`${p.default}\``;
};

function renderMethod(m) {
  const out = [];
  const badge = isObsolete(m.doc) ? ' <Badge type="warning" text="obsolete" />' : '';
  out.push(`### \`${m.name}\`${badge}`, '');
  for (const para of m.doc) out.push(prose(para), '');
  if (m.params.length) {
    out.push('| Parameter | Type | Default | Description |', '|---|---|---|---|');
    for (const p of m.params) {
      out.push(`| \`${p.name}\` | \`${cell(p.type)}\` | ${defaultCell(p)} | ${p.doc ? cell(p.doc) : ''} |`);
    }
    out.push('');
    if (m.preferred) out.push(`Preferred parameter: \`${m.preferred}\` — a positional call passes it.`, '');
  }
  if (m.returning) out.push(`Returns \`${m.returning.type}\`.`, '');
  return out;
}

/** Every constant of a group as its full spelled form, nested groups
 *  flattened the way a page writes them: cs_device-system-phone. */
function constantRows(group, prefix, rows) {
  for (const member of group.members) {
    if (member.members) constantRows(member, `${prefix}-${member.name}`, rows);
    else rows.push({ name: `${prefix}-${member.name}`, value: member.value ?? '', label: member.label });
  }
  return rows;
}

function renderConstants(group) {
  const out = [`### \`${group.name}\``, ''];
  for (const para of group.doc) out.push(prose(para), '');
  const rows = constantRows(group, group.name, []);
  const labelled = rows.some((r) => r.label);
  out.push(labelled ? '| Constant | Value | |' : '| Constant | Value |');
  out.push(labelled ? '|---|---|---|' : '|---|---|');
  for (const r of rows) {
    const value = r.value === '' ? '*(empty)*' : `\`${cell(r.value)}\``;
    out.push(`| \`${r.name}\` | ${value} |${labelled ? ` ${r.label ? `*${cell(r.label)}*` : ''} |` : ''}`);
  }
  out.push('');
  return out;
}

function renderType(t) {
  const out = [`### \`${t.name}\``, ''];
  for (const para of t.doc ?? []) out.push(prose(para), '');
  if (t.members) {
    out.push('| Field | Type |', '|---|---|');
    for (const f of t.members) out.push(`| \`${f.name}\` | \`${cell(f.type)}\` |`);
    out.push('');
  } else {
    out.push(`Defined as \`${t.definition}\`.`, '');
  }
  return out;
}

const groups = new Map();
for (const name of ORDER) groups.set(name, []);
for (const m of model.methods) groups.get(m.group).push(m);

const body = [
  START,
  '',
  `Generated from [\`z2ui5_if_client\`](https://github.com/abap2UI5/abap2UI5/blob/${REF}/${interfacePath})`,
  `at release **${REF}** — ${model.methods.length} methods, ${model.constants.length} constant`,
  `structures. The same reference as one JSON document: [client-api.json](${SITE}/api/client-api.json).`,
  '',
  ...[...groups].filter(([, list]) => list.length).flatMap(([name, list]) => [
    `## ${name}`,
    '',
    ...list.flatMap(renderMethod),
  ]),
  '## Constants',
  '',
  'The values an app compares against or passes on: `cs_event` names every',
  'frontend action, `cs_view` the view slots, `cs_device` what `get( )` reports',
  'about the device, `cs_nav_mode` the routing modes.',
  '',
  ...model.constants.flatMap(renderConstants),
  '## Types',
  '',
  ...model.types.flatMap(renderType),
  END,
].join('\n');

if (body.includes('{{')) {
  // `{{` is Vue interpolation in a VitePress page, even in prose
  console.error('the generated markdown contains `{{`, which VitePress hands to Vue - fix the renderer.');
  process.exit(1);
}

/* -------------------------------------------------------------------- JSON */

const json = `${JSON.stringify({
  description: 'The abap2UI5 client API: everything an app may call on `client`, '
    + 'read from z2ui5_if_client at the release this documentation names.',
  release: REF,
  source: `https://github.com/abap2UI5/abap2UI5/blob/${REF}/${interfacePath}`,
  documentation: `${SITE}/resources/api.html`,
  methods: model.methods.map(({ name, group, doc, preferred, params, returning }) => ({
    name,
    group,
    ...(doc.length ? { doc } : {}),
    ...(preferred ? { preferred } : {}),
    parameters: params,
    ...(returning ? { returns: returning.type } : {}),
  })),
  constants: model.constants,
  types: model.types,
}, null, 2)}\n`;

/* --------------------------------------------------------------------- run */

if (!fs.existsSync(PAGE)) {
  console.error(`${path.relative(ROOT, PAGE)}: gone - the intro around the generated block is`);
  console.error('hand-written, so this script does not create the page, only the block in it.');
  process.exit(1);
}
const page = fs.readFileSync(PAGE, 'utf8');
const from = page.indexOf(START);
const to = page.indexOf(END, from);
if (from === -1 || to === -1) {
  console.error(`${path.relative(ROOT, PAGE)}: no ${from === -1 ? 'start' : 'end'} marker - restore the marker pair, then rerun.`);
  process.exit(1);
}
const nextPage = page.slice(0, from) + body + page.slice(to + END.length);
const currentJson = fs.existsSync(JSON_OUT) ? fs.readFileSync(JSON_OUT, 'utf8') : null;

console.log(`z2ui5_if_client at ${REF}: ${model.methods.length} methods in ${[...groups.values()].filter((l) => l.length).length} groups, `
  + `${model.constants.length} constant structures, ${model.types.length} types`);

if (CHECK) {
  const stale = [];
  if (nextPage !== page) stale.push(path.relative(ROOT, PAGE));
  if (json !== currentJson) stale.push(path.relative(ROOT, JSON_OUT));
  if (stale.length) {
    console.error(`\nout of date against abap2UI5 ${REF}:`);
    for (const f of stale) console.error(`  ${f}`);
    console.error('\nThe interface changed under the committed reference - or the reference was');
    console.error('edited by hand. Run `npm run generate:api` and commit what it writes.');
    process.exit(1);
  }
  console.log('the committed API reference matches the interface at that release - OK');
} else {
  fs.mkdirSync(path.dirname(JSON_OUT), { recursive: true });
  const wrote = [];
  if (nextPage !== page) { fs.writeFileSync(PAGE, nextPage); wrote.push(path.relative(ROOT, PAGE)); }
  if (json !== currentJson) { fs.writeFileSync(JSON_OUT, json); wrote.push(path.relative(ROOT, JSON_OUT)); }
  console.log(wrote.length ? `rewritten: ${wrote.join(', ')}` : 'already up to date - nothing written.');
}
