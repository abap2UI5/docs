/** Every British spelling in the prose of `markdown`: line and column
 *  (1-based), the word, and the American form. */
export function findBritish(markdown) {
  const found = [];
  proseLines(markdown).forEach((line, i) => {
    const taken = [];
    const free = (a, b) => !taken.some(([s, e]) => a < e && b > s);
    for (const [re, american, stemIs] of BRITISH) {
      for (const m of line.matchAll(re)) {
        const [start, end] = [m.index, m.index + m[0].length];
        if (!free(start, end)) continue;
        if (stemIs && !stemIs(m[1])) continue;
        taken.push([start, end]);
        found.push({ line: i + 1, col: start + 1, word: m[0], american: american(m[0]) });
      }
    }
  });
  return found.sort((a, b) => a.line - b.line || a.col - b.col);
}

/** `markdown` with every British spelling in its prose replaced - and only
 *  there: the offsets come from the blanked lines and are applied to the
 *  original ones. */
export function americanize(markdown) {
  const lines = markdown.split('\n');
  const hits = findBritish(markdown);
  for (let k = hits.length - 1; k >= 0; k--) {
    const { line, col, word, american } = hits[k];
    const at = lines[line - 1];
    lines[line - 1] = at.slice(0, col - 1) + american + at.slice(col - 1 + word.length);
  }
  return lines.join('\n');
}
