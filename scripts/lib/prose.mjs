/* The words of a page that are PROSE - what a reader reads, as opposed to
 * what a compiler or a browser reads - and the house spelling of them.
 *
 * Fenced code, inline code, link targets, HTML tags and comments, bare URLs,
 * generated blocks and the frontmatter (all but its title and description,
 * which a search result shows) are blanked out, character for character, so a
 * match in what
 * comes back sits at the same offset in the original line: a spelling can be
 * checked, or corrected, without ever touching an ABAP keyword, a CSS property
 * or a path.
 *
 * Shared by test/spelling.test.mjs, which is the gate, and by
 * scripts/fix-spelling.mjs, which rewrites a page towards the rule. */

import { readdirSync } from 'node:fs';
import { join } from 'node:path';

/** Every page of the manual under `docs/`: not `public` (a generated copy of
 *  each page) and not a dot-directory (`.vitepress`, with the build in it). */
export const manualPages = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
  e.isDirectory() ? (e.name === 'public' || e.name.startsWith('.') ? [] : manualPages(join(dir, e.name)))
    : e.name.endsWith('.md') ? [join(dir, e.name)] : []);

const blank = (s) => ' '.repeat(s.length);

/** Each line of `markdown` with everything that is not prose replaced by
 *  spaces of the same length. */
export function proseLines(markdown) {
  const lines = markdown.split('\n');
  const out = [];
  let fence = null;
  let comment = false;
  let generated = false;
  let front = lines[0] === '---' ? 'open' : null;
  for (const line of lines) {
    /* A block a generator wrote - the API reference out of z2ui5_if_client,
       the Working Samples out of a catalog - is that generator's to spell:
       a correction here would be undone by its next run, or fail its
       freshness gate. The markers are the generators' own. */
    if (generated) {
      out.push(blank(line));
      if (/^<!-- \w+:end -->/.test(line)) generated = false;
      continue;
    }
    if (/^<!-- \w+:start \(generated by /.test(line)) {
      out.push(blank(line));
      generated = true;
      continue;
    }
    if (front === 'open') {
      /* The title and the description are what a search result and a preview
         card show, and a reader reads them; the rest of the frontmatter is
         configuration. */
      const shown = line.match(/^(title|description):\s*/);
      out.push(shown ? blank(shown[0]) + line.slice(shown[0].length) : blank(line));
      if (line === '---' && out.length > 1) front = 'closed';
      continue;
    }
    const opening = line.match(/^\s*(`{3,}|~{3,})/);
    if (fence) {
      out.push(blank(line));
      if (opening && opening[1][0] === fence[0] && opening[1].length >= fence.length) fence = null;
      continue;
    }
    if (opening) {
      fence = opening[1];
      out.push(blank(line));
      continue;
    }
    /* An HTML comment that runs over several lines: a maintainer's note, and
       one that may quote the very code the rule must not touch. */
    let text = line;
    if (comment) {
      const close = text.indexOf('-->');
      if (close === -1) { out.push(blank(text)); continue; }
      text = blank(text.slice(0, close + 3)) + text.slice(close + 3);
      comment = false;
    }
    text = text.replace(/<!--[\s\S]*?-->/g, blank);
    const open = text.indexOf('<!--');
    if (open !== -1) { text = text.slice(0, open) + blank(text.slice(open)); comment = true; }
    out.push(text
      .replace(/`[^`]*`/g, blank)
      .replace(/\]\([^)]*\)/g, blank)
      .replace(/<[^>]+>/g, blank)
      .replace(/https?:\/\/\S+/g, blank));
  }
  return out;
}

/* ---- the house spelling -----------------------------------------------
 *
 * American. The manual is read by people whose systems are SAP's, and SAP
 * writes "authorization", "Customizing", "behavior definition" and "catalog";
 * a manual that spelled its own prose the other way would teach a reader to
 * search for words their system does not use. It was mixed for years - 15
 * behaviours against 39 behaviors, in the same chapter sometimes - which is
 * what makes a rule worth a test: a decision that lives only in a document
 * wanders back the next time somebody pastes a paragraph.
 *
 * Each rule is a pattern and the American form of what it matched. The
 * patterns are the BRITISH forms, because that is the direction the drift
 * runs; `-ise` and `-isation` are matched in general with the words that are
 * `-ise` in both spellings listed out, and a word this list has not met is
 * reported rather than passed - the message names it, and the list is where
 * to add it. */

const keepCase = (like, word) => {
  if (!word) return word;
  if (like === like.toUpperCase() && like.length > 1) return word.toUpperCase();
  if (like[0] === like[0].toUpperCase()) return word[0].toUpperCase() + word.slice(1);
  return word;
};
/* The tail of a word replaced, in the case the tail was written in. */
const tailed = (re, map) => (w) => w.replace(re, (t) => keepCase(t, map[t.toLowerCase()]));
const mapped = (map) => (w) => keepCase(w, map[w.toLowerCase()]);
const exact = (map) => [
  new RegExp(`\\b(?:${Object.keys(map).join('|')})\\b`, 'gi'),
  mapped(map),
];

/* Words that end in -ise in American English too, as the stem before "is":
   "surpr" for surprise, "prom" for promise. Some are the whole stem (rise,
   arise, disable, crises), some its end (unsurprised, disenfranchise), and
   four families go by the stem's last letter - ...wise, ...aise, ...oise,
   ...uise - because no British verb lives there. */
const ISE_IN_BOTH = (stem) =>
  /^(?:r|ar|d|v|cr|el|ir|upr|sunr|moonr|exorc|circumc|telev|superv|inc|exc|conc|prec|dem|mort|val|chem|cer|an|treat|parad|expert|chast|desp)$/i.test(stem)
  || /(?:prom|prem|adv|advert|rev|dev|exerc|franch|merchand|comprom|improv|surpr|compr|enterpr|repr|appr|surm)$|[waou]$/i.test(stem);

