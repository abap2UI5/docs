#!/usr/bin/env node
/*
 * generate-controls-reference — the custom controls as a page, generated
 * from their source.
 *
 * The frontend ships seventeen controls under app/webapp/cc/ that a view
 * reaches as `<z2ui5:Name>`: a camera, a file uploader, the device position,
 * a WebSocket, the Excel bridge, the dirty flag. Each declares what an app
 * can bind and wire in its UI5 metadata - properties with a type and a
 * default, events with their parameters, aggregations - and no page listed
 * any of it: a reader found a control in a cookbook example and opened the
 * JavaScript to learn its second property.
 *
 * So the reference is GENERATED, the way resources/api.md is from
 * z2ui5_if_client: one section per control, between markers in
 * docs/resources/controls.md, read from the framework at the ref every API
 * gate uses (lib/release.mjs, frameworkRef - main; A2UI5_REF pins a run back,
 * A2UI5_HOME reads a clone). The metadata is read by RUNNING each module in
 * an empty vm with stand-in dependencies (lib/controls.mjs says why a regex
 * is the wrong tool for it).
 *
 * Each section links the page of this manual that uses the control, found
 * by walking the pages for `z2ui5:Name`, `z2ui5.cc.Name` or the builder's
 * `` `Name` … ns = `z2ui5` `` - so a cookbook page that starts using a
 * control changes this block too, and --check says to regenerate. That is
 * deliberate: a hand-kept map of control to page is the ledger that goes
 * stale.
 *
 * Committed, and held fresh by --check like the API reference: regenerate
 * and compare byte for byte. When the framework cannot be reached, --check
 * SAYS SO and passes; generation without --check fails, there is nothing to
 * write.
 *
 *   node scripts/generate-controls-reference.mjs            rewrite the block
 *   node scripts/generate-controls-reference.mjs --check    fail if a rewrite
 *                                                           would change anything
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { frameworkRef } from './lib/release.mjs';
import { frameworkHome } from './lib/client-interface.mjs';
import { fetchControls, usesControl, controlsDir, NAMESPACE } from './lib/controls.mjs';
import { cell, codeSpan } from './lib/api-markdown.mjs';
import { markdownFiles, linkOf, DOCS } from './lib/pages.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = path.join(ROOT, 'docs', 'resources', 'controls.md');
const CHECK = process.argv.includes('--check');

const START = '<!-- controls:start (generated by scripts/generate-controls-reference.mjs — do not edit) -->';
const END = '<!-- controls:end -->';

/* Seventeen today. Fewer than this and the listing or the reader broke, not
 * the framework shrank by half. */
const FLOOR = 10;

/* Pages whose mention of a control is not a use of it: the record of what
 * changed, the record of what went, this page itself, and the client API. */
const NOT_A_USE = new Set(['/resources/changelog', '/resources/deprecations', '/resources/controls', '/resources/api']);

/* ------------------------------------------------------------- the source */

const REF = frameworkRef();
let controls;
try {
  controls = await fetchControls(REF);
  const home = frameworkHome();
  console.log(`read ${controlsDir}/*.js at ${REF} ${home ? `in the clone at ${home} (A2UI5_HOME)` : 'from github.com'}`);
} catch (err) {
  console.log(`${controlsDir} at ${REF}: not resolved (${err.message})`);
  if (CHECK) {
    console.log('SKIPPED: nothing was verified.');
    process.exit(0);
  }
  console.error('nothing to generate from - try again with a network, or point A2UI5_HOME at a clone of abap2UI5/abap2UI5.');
  process.exit(1);
}
if (controls.length < FLOOR) {
  console.error(`${controlsDir} at ${REF}: ${controls.length} control(s) read - the listing or the module shape changed.`);
  console.error('Fix scripts/lib/controls.mjs, or this reference silently thins out.');
  process.exit(1);
}

/* ------------------------------------------------------- where it is used */

const pages = markdownFiles(DOCS)
  .map((file) => ({ link: linkOf(file), text: fs.readFileSync(file, 'utf8') }))
  .filter((p) => !NOT_A_USE.has(p.link))
  .sort((a, b) => a.link.localeCompare(b.link));

/** The H1 of a page, for the link text. */
const titleOf = (text) => /^#\s+(.+)$/m.exec(text)?.[1]?.trim() ?? null;

/* ---------------------------------------------------------------- markdown */

const code = (s) => codeSpan(String(s));

const defaultCell = (p) => {
  if (p.defaultValue === undefined) return '';
  if (p.defaultValue === null) return '`null`';
  if (p.defaultValue === '') return '*(empty)*';
  if (typeof p.defaultValue === 'string' && p.defaultValue.startsWith('(')) return `*${p.defaultValue}*`;
  return code(typeof p.defaultValue === 'object' ? JSON.stringify(p.defaultValue) : p.defaultValue);
};

function renderControl(c) {
  const out = [`## \`${c.tag}\``, ''];
  if (c.summary) out.push(cell(c.summary), '');
  const base = c.base ? ` Extends \`${c.base.replace(/\//g, '.')}\`.` : '';
  out.push(`Module \`${c.fullName}\` ([source](https://github.com/abap2UI5/abap2UI5/blob/${REF}/${c.file})).${base}`, '');
  const used = pages.filter((p) => usesControl(p.text, c.name));
  if (used.length) {
    out.push(`Used on ${used.map((p) => `[${titleOf(p.text) ?? p.link}](${p.link})`).join(', ')}.`, '');
  }
  if (c.properties.length) {
    out.push('| Property | Type | Default |', '|---|---|---|');
    for (const p of c.properties) out.push(`| \`${p.name}\` | \`${cell(p.type)}\` | ${defaultCell(p)} |`);
    out.push('');
  } else {
    out.push('No properties of its own.', '');
  }
  if (c.events.length) {
    out.push('| Event | Parameters |', '|---|---|');
    for (const e of c.events) {
      const params = e.parameters.length ? e.parameters.map((p) => `\`${p.name}\` (\`${cell(p.type)}\`)`).join(', ') : '*none*';
      out.push(`| \`${e.name}\` | ${params}${e.allowPreventDefault ? ' — may be prevented' : ''} |`);
    }
    out.push('');
  } else {
    out.push('No events of its own.', '');
  }
  if (c.aggregations.length) {
    out.push('| Aggregation | Type | |', '|---|---|---|');
    for (const a of c.aggregations) {
      const notes = [a.multiple ? 'multiple' : 'single', ...(a.visibility ? [a.visibility] : []), ...(c.defaultAggregation === a.name ? ['default'] : [])];
      out.push(`| \`${a.name}\` | \`${cell(a.type)}\` | ${notes.join(', ')} |`);
    }
    out.push('');
  }
  return out;
}

const body = [
  START,
  '',
  `Generated from [\`${controlsDir}\`](https://github.com/abap2UI5/abap2UI5/tree/${REF}/${controlsDir})`,
  `on **${REF}** — ${controls.length} controls, every one under \`xmlns:z2ui5="${NAMESPACE}"\`.`,
  '',
  ...controls.flatMap(renderControl),
  END,
].join('\n');

if (body.includes('{{')) {
  console.error('the generated markdown contains `{{`, which VitePress hands to Vue - fix the renderer.');
  process.exit(1);
}

/* --------------------------------------------------------------------- run */

if (!fs.existsSync(PAGE)) {
  console.error(`${path.relative(ROOT, PAGE)}: gone - the intro around the generated block is`);
  console.error('hand-written, so this script does not create the page, only the block in it.');
  process.exit(1);
}
const page = fs.readFileSync(PAGE, 'utf8');
const from = page.indexOf(START);
const to = page.indexOf(END, from);
if (from === -1 || to === -1) {
  console.error(`${path.relative(ROOT, PAGE)}: no ${from === -1 ? 'start' : 'end'} marker - restore the marker pair, then rerun.`);
  process.exit(1);
}
const nextPage = page.slice(0, from) + body + page.slice(to + END.length);

console.log(`${controls.length} controls at ${REF}: ${controls.reduce((n, c) => n + c.properties.length, 0)} properties, `
  + `${controls.reduce((n, c) => n + c.events.length, 0)} events, `
  + `${controls.filter((c) => pages.some((p) => usesControl(p.text, c.name))).length} used on a page of this site`);

if (CHECK) {
  if (nextPage !== page) {
    console.error(`\nout of date against abap2UI5 ${REF}: ${path.relative(ROOT, PAGE)}`);
    console.error('\nA control changed under the committed reference, a page started or stopped using');
    console.error('one, or the block was edited by hand. Run `npm run generate:controls` and commit');
    console.error('what it writes.');
    process.exit(1);
  }
  console.log('the committed controls reference matches the source at that ref - OK');
} else {
  if (nextPage !== page) {
    fs.writeFileSync(PAGE, nextPage);
    console.log(`rewritten: ${path.relative(ROOT, PAGE)}`);
  } else {
    console.log('already up to date - nothing written.');
  }
}
